import { NextResponse } from "next/server";
import { promises as fs } from "fs";
import path from "path";
import { cacheGetJSON, cacheSetJSON } from "@/lib/latent/cache";

// Batch signals endpoint — iterates all 361 stocks in ml_predictions_multi.json,
// uses the CL Ensemble consensus (cl_ensemble_predictions) per stock, filters to
// BUY/SELL signals with R:R ≥ 2 (reward ≥ 2× risk, using TP3 (21-day target) as the reward target),
// and returns the list sorted by R:R descending.
//
// This endpoint is the single source of truth for both the Dashboard's "active
// signals" count and the SignalSection's signal grid — so the two views always
// agree on what counts as an actionable signal.
//
// Algorithm:
//   1. Read ml_predictions_multi.json
//   2. For each symbol in cl_ensemble_predictions:
//      - Pull { signal, entry, sl, tp1, tp2, tp3, confidence, currentPrice }
//      - Skip if signal is HOLD or invalid
//      - Compute R:R = |tp3 - entry| / |entry - sl|
//      - Skip if R:R < 2 (sub-1:2 setups filtered out)
//   3. Return sorted by R:R descending

export const dynamic = "force-dynamic";
export const maxDuration = 30;

const CACHE_KEY = "signals:all";
const MIN_RISK_REWARD = 2; // 1:2 minimum → reward ≥ 2× risk

interface ClPrediction {
  signal: "BUY" | "SELL" | "HOLD";
  direction: "LONG" | "SHORT";
  confidence: number;
  currentPrice: number;
  entry: number;
  tp1: number;
  tp2: number;
  tp3: number;
  sl: number;
  avgReturn?: number;
}

export interface StockSignalSummary {
  symbol: string;
  stockName: string;
  signal: "BUY" | "SELL";
  direction: "LONG" | "SHORT";
  confidence: number;
  currentPrice: number;
  entry: number;
  sl: number;
  tp1: number;
  tp2: number;
  tp3: number;
  riskReward: number; // |tp3 - entry| / |entry - sl|
  avgReturn: number;
}

function computeRiskReward(entry: number, tp3: number, sl: number): number {
  const reward = Math.abs(tp3 - entry);
  const risk = Math.abs(entry - sl);
  if (risk <= 0) return 0;
  return reward / risk;
}

// Minimal symbol → company-name map. The askanalyst company list is fetched
// client-side by StockSearch, so for the batch endpoint we just use the
// prediction file's symbol (uppercase). The Dashboard/SignalSection can
// resolve the full company name on the client via StockSearch's companies.
function buildSignalList(multi: any): StockSignalSummary[] {
  const clEns: Record<string, ClPrediction> | undefined = multi?.cl_ensemble_predictions;
  if (!clEns) return [];

  const out: StockSignalSummary[] = [];
  for (const [symbol, pred] of Object.entries(clEns)) {
    if (!pred) continue;
    const signal = pred.signal;
    if (signal !== "BUY" && signal !== "SELL") continue;

    const entry = typeof pred.entry === "number" ? pred.entry : 0;
    const sl = typeof pred.sl === "number" ? pred.sl : 0;
    const tp1 = typeof pred.tp1 === "number" ? pred.tp1 : 0;
    const tp2 = typeof pred.tp2 === "number" ? pred.tp2 : 0;
    const tp3 = typeof pred.tp3 === "number" ? pred.tp3 : 0;
    const currentPrice = typeof pred.currentPrice === "number" ? pred.currentPrice : entry;

    // Guard: invalid trade params (zero entry/sl/tp3 → would div-by-zero or be junk)
    if (entry <= 0 || sl <= 0 || tp3 <= 0) continue;

    const rr = computeRiskReward(entry, tp3, sl);
    if (rr < MIN_RISK_REWARD) continue;

    out.push({
      symbol,
      stockName: symbol, // client resolves full name via StockSearch/companies API
      signal,
      direction: pred.direction === "SHORT" ? "SHORT" : "LONG",
      confidence: typeof pred.confidence === "number" ? pred.confidence : 0,
      currentPrice,
      entry,
      sl,
      tp1,
      tp2,
      tp3,
      riskReward: rr,
      avgReturn: typeof pred.avgReturn === "number" ? pred.avgReturn : 0,
    });
  }

  // Sort by R:R descending (highest reward-to-risk first)
  out.sort((a, b) => b.riskReward - a.riskReward);
  return out;
}

export async function GET() {
  const start = Date.now();

  // Cache for 5 minutes — the underlying predictions file is regenerated by a
  // daily cron, so caching the filtered list keeps the dashboard snappy.
  const cached = await cacheGetJSON<{ signals: StockSignalSummary[]; generatedAt: string }>(CACHE_KEY);
  if (cached) {
    return NextResponse.json({
      ...cached,
      cached: true,
      latencyMs: Date.now() - start,
    });
  }

  let multi: any = null;
  try {
    const filePath = path.join(process.cwd(), "data", "ml_predictions_multi.json");
    multi = JSON.parse(await fs.readFile(filePath, "utf-8"));
  } catch {
    return NextResponse.json(
      { error: "Predictions file not found. Run: python3 scripts/train_all_with_backtesting.py" },
      { status: 503 }
    );
  }

  const signals = buildSignalList(multi);
  const resp = {
    signals,
    count: signals.length,
    buyCount: signals.filter((s) => s.signal === "BUY").length,
    sellCount: signals.filter((s) => s.signal === "SELL").length,
    minRiskReward: MIN_RISK_REWARD,
    generatedAt: multi?.trained_at || new Date().toISOString(),
    stocksScanned: Object.keys(multi?.cl_ensemble_predictions || {}).length,
  };

  await cacheSetJSON(CACHE_KEY, resp, 300); // 5-minute TTL
  return NextResponse.json({ ...resp, cached: false, latencyMs: Date.now() - start });
}
