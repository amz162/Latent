import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();
const total = await prisma.stock.count();
const withPrice = await prisma.stock.count({ where: { price: { not: null } } });
const bySource = await prisma.stock.groupBy({ by: ["source"], _count: { source: true } });
const inStocksApi = await (await fetch("https://psxdata-api.fastapicloud.dev/stocks")).json();
const apiSet = new Set(inStocksApi.data.map(String));
const dbSyms = (await prisma.stock.findMany({ select: { symbol: true } })).map(s => s.symbol);
const onlyInDb = dbSyms.filter(s => !apiSet.has(s));
console.log(`DB total: ${total}`);
console.log(`DB with price: ${withPrice}`);
console.log(`DB without price: ${total - withPrice}`);
console.log(`/stocks API count: ${apiSet.size}`);
console.log(`Symbols only in DB (not in /stocks): ${onlyInDb.length}`);
console.log(`Sample of "only in DB":`, onlyInDb.slice(0, 10));
console.log("By source:");
for (const r of bySource) console.log(`  ${r.source}: ${r._count.source}`);
const sectors = await prisma.sector.count();
console.log(`Sectors: ${sectors}`);
await prisma.$disconnect();
